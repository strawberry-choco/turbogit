/// An icon at `size` points, stroked in `color` (its `currentColor`).
pub fn icon(name: Icon, size: f32, color: AdaptiveColor) -> impl IntoElement {
    svg(ImageSrc::svg_markup(name.markup()))
        .w(px(size))
        .h(px(size))
        .flex_shrink_0()
        .text_color(color)
}

/// An icon that inherits the ink of the view it sits in, so a control's
/// hover can move the icon with its label.
pub fn icon_current(name: Icon, size: f32) -> impl IntoElement {
    svg(ImageSrc::svg_markup(name.markup()))
        .w(px(size))
        .h(px(size))
        .flex_shrink_0()
}
